const VERSION = new URL(self.location.href).searchParams.get('v') || 'dev';
const STATIC = `hs-v2-${VERSION}-${PRECACHE.hash}`;
const APP = `hs-v2-app-${VERSION}`;
const SCOPE = new URL(self.registration ? self.registration.scope : './', self.location.href);
const NET_WAIT_MS = 6000;
const HEAVY = /\.(task|wasm)$/;           // models + wasm: precached only when the page says it uses them
const inflight = new Map();               // url → settles when a cache-first fetch of it is stored (or failed)

async function precache(cacheName, list) {
  const cache = await caches.open(cacheName);
  await Promise.all(list.map(async p => {
    const url = new URL(p, SCOPE).href;
    if (cacheName === STATIC) {
      if (inflight.has(url)) await inflight.get(url);              // the page is downloading it right now
      if (await cache.match(url)) return;                          // already there (same content hash)
    }
    // no-cache: revalidate with the server (a 304 reuses the copy the page itself just downloaded)
    const res = await fetch(new Request(url, { cache: 'no-cache' }));
    if (!res.ok || res.status !== 200) throw new Error(`precache ${res.status} ${p}`);
    await cache.put(url, res);
  }));
}

self.addEventListener('install', e => {
  self.skipWaiting();
  e.waitUntil(precache(APP, PRECACHE.app));
});

/** Static set: every light file + the heavy files (model, wasm) the page named. Paths only under vendor/ models/. */
function staticList(files) {
  const named = [];
  for (const f of Array.isArray(files) ? files : []) {
    let u; try { u = new URL(String(f), SCOPE); } catch (e) { continue; }
    if (u.origin !== SCOPE.origin || !u.pathname.startsWith(SCOPE.pathname) || !isStatic(u.pathname) || !HEAVY.test(u.pathname)) continue;
    named.push(u.pathname.slice(SCOPE.pathname.length));
  }
  return [...new Set([...PRECACHE.static.filter(p => !HEAVY.test(p)), ...named])];
}

self.addEventListener('message', e => {
  if (e.data?.t !== 'precache') return;
  const job = precache(STATIC, staticList(e.data.files)).catch(err => console.warn('[sw] precache', err?.message || err));
  e.waitUntil?.(job);
});

self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(n => n.startsWith('hs-v2-') && n !== STATIC && n !== APP).map(n => caches.delete(n)));
    await self.clients.claim();
  })());
});

function isStatic(path) {
  const rel = path.slice(SCOPE.pathname.length);
  return rel.startsWith('vendor/') || rel.startsWith('models/');
}

async function cacheFirst(req) {
  const cache = await caches.open(STATIC);
  const hit = await cache.match(req, { ignoreSearch: true });
  if (hit) return hit;
  const key = req.url.split('?')[0];
  let settle; const stored = new Promise(r => { settle = r; });
  if (!inflight.has(key)) inflight.set(key, stored);
  const done = () => { settle(); if (inflight.get(key) === stored) inflight.delete(key); };
  let res;
  try { res = await fetch(req); } catch (e) { done(); throw e; }
  if (res.ok && res.status === 200) cache.put(req, res.clone()).catch(() => {}).finally(done);
  else done();
  return res;
}

// clientId → 'cache' | 'net': where that page (or worker) got its own document / script from
const clientSource = new Map();
let lastNavSource = null;   // for a client the map does not know (a browser without worker resultingClientId)
function rememberSource(id, src) {
  if (!id) return;
  clientSource.delete(id); clientSource.set(id, src);
  while (clientSource.size > 64) clientSource.delete(clientSource.keys().next().value);   // oldest first
}

/** @param {'navigate'|'net'|'cache'} how  navigate = network, cached copy if slower than NET_WAIT_MS;
 *  net = network, cached copy only on a network error; cache = cached copy first (page came from the cache) */
async function networkFirst(req, how = 'net') {
  const cache = await caches.open(APP);
  const cached = () => cache.match(req, { ignoreSearch: req.mode === 'navigate' });
  if (how === 'cache') {
    const hit = await cached();
    if (hit) return { res: hit, src: 'cache' };
  }
  const net = fetch(req, { cache: 'no-cache' }).then(res => {
    if (res.ok && res.status === 200) cache.put(req, res.clone()).catch(() => {});
    return res;
  });
  net.catch(() => {});   // a lost race must not log an unhandled rejection
  let timer = 0;
  try {
    const race = [net];
    if (how === 'navigate') race.push(new Promise((_, rej) => { timer = setTimeout(() => rej(new Error('slow')), NET_WAIT_MS); }));
    return { res: await Promise.race(race), src: 'net' };
  } catch (e) {
    const hit = await cached();
    if (hit) return { res: hit, src: 'cache' };
    return { res: await net, src: 'net' };   // no copy: keep waiting for the network (or its error)
  } finally { clearTimeout(timer); }
}

async function appRequest(e) {
  const req = e.request;
  const nav = req.mode === 'navigate';
  const parent = clientSource.get(e.clientId) || lastNavSource;
  // a worker script follows the page that starts it; its own imports then follow the worker
  const how = nav ? 'navigate' : parent === 'cache' ? 'cache' : 'net';
  const { res, src } = await networkFirst(req, how);
  if (nav) lastNavSource = src;
  if (e.resultingClientId) rememberSource(e.resultingClientId, nav ? src : (parent || src));
  return res;
}

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || req.headers.has('range')) return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  if (/^\/(api|ws|c)(\/|$)/.test(url.pathname.slice(SCOPE.pathname.length - 1))) return;
  if (url.pathname.endsWith('/sw.js')) return;
  e.respondWith(isStatic(url.pathname) ? cacheFirst(req) : appRequest(e));
});
